/**
 * Shared blog post components — the single source of truth for the markup that
 * every post's "post footer" region contains.
 *
 * Posts are standalone HTML files (no build step / no server-side templating),
 * so "template-driven" here means: this module renders the markup,
 * `scripts/sync_blog_components.ts` writes it into every post between the
 * BEGIN/END markers, and `blog_components_test.ts` fails if any post drifts.
 *
 * To add a post: add it to `blog_posts.ts`, add an entry here, run
 * `deno task sync:posts`. Never hand-edit the generated block in a post.
 */

