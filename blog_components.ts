/**
 * Marker comments delimiting the generated region inside each post.
 * The sync script matches on the prefix so the trailing note can be reworded
 * without stranding already-generated blocks.
 */
export const BEGIN_MARKER_PREFIX = "<!-- BEGIN post-components";
export const BEGIN_MARKER =
  `${BEGIN_MARKER_PREFIX}: generated by scripts/sync_blog_components.ts — edit blog_components.ts, not this block -->`;
export const END_MARKER = "<!-- END post-components -->";

export interface PostComponents {
  /** Counterpart post path, or null when no translation exists yet. */
  altPath: string | null;
  /** Switcher copy; null when there is no counterpart. */
  switchCopy: { lead: string; anchor: string } | null;
  /** 5–8 post-specific schema.org keywords. */
  keywords: string;
  /**
   * schema.org `about` Thing names for this post. Kept in English on ES posts
   * too: these are entity names for crawlers, not reader-facing copy.
   */
  about: string[];
}

