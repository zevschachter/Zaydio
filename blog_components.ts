/** Posts still waiting on a translation — surfaced as a content TODO, never invented. */
export function postsMissingTranslation(): BlogPost[] {
  return BLOG_POSTS.filter((p) => POST_COMPONENTS[p.path]?.altPath == null);
}

/** Helpful-API slug for a post path: `/blog/foo/` -> `blog/foo`. */
export function helpfulSlugForPath(path: string): string {
  return path.replace(/^\/+/, "").replace(/\/+$/, "");
}

/** Repo-relative HTML file for a post path. */
export function fileForPath(path: string): string {
  return `.${path}index.html`;
}

const HELPFUL_COPY = {
  en: {
    ariaLabel: "Mark this post as helpful",
    label: "This helped",
  },
  es: {
    ariaLabel: "Marcar este artículo como útil",
    label: "Esto ayudó",
  },
} as const;

function indentLines(html: string, indent: string): string {
  return html
    .split("\n")
    .map((line) => (line.length > 0 ? indent + line : line))
    .join("\n");
}

/**
 * schema.org `about` array, formatted to match the hand-written JSON-LD in the
 * existing posts (4-space nesting, trailing comma so it can precede a sibling).
 */
export function renderSchemaAbout(names: string[], indent: string): string {
  const things = names.map((name) =>
    [
      `${indent}    {`,
      `${indent}        "@type": "Thing",`,
      `${indent}        "name": "${name}"`,
      `${indent}    }`,
    ].join("\n")
  );
  return [
    `${indent}"about": [`,
    things.join(",\n"),
    `${indent}],`,
  ].join("\n");
}

/** Contextual EN<->ES switcher. Empty string when no counterpart exists. */
export function renderLangSwitch(post: BlogPost): string {
  const config = POST_COMPONENTS[post.path];
  if (!config?.altPath || !config.switchCopy) return "";
  const targetLang = post.lang === "en" ? "es" : "en";
  const { lead, anchor } = config.switchCopy;
  return [
    `<p class="blog-lang-switch" lang="${targetLang}">${lead} &rarr; ` +
    `<a href="${config.altPath}" hreflang="${targetLang}" lang="${targetLang}">${anchor}</a></p>`,
  ].join("\n");
}

/** Thumbs-up "this helped" control. Reuses the existing /api/helpful counter. */
export function renderHelpfulWidget(post: BlogPost): string {
  const copy = HELPFUL_COPY[post.lang];
  const slug = helpfulSlugForPath(post.path);
  return [
    `<div class="blog-helpful" data-helpful data-lang="${post.lang}" data-slug="${slug}">`,
    `    <button type="button" class="blog-helpful-btn" aria-label="${copy.ariaLabel}">`,
    `        <picture>`,
    `            <source type="image/webp" srcset="/blog/zaydio-thumbs-up-128.webp 1x, /blog/zaydio-thumbs-up-256.webp 2x, /blog/zaydio-thumbs-up-512.webp 4x">`,
    `            <img class="blog-helpful-thumb" src="/blog/zaydio-thumbs-up-256.png" width="64" height="128" alt="" aria-hidden="true" loading="lazy" decoding="async">`,
    `        </picture>`,
    `    </button>`,
    `    <span class="blog-helpful-label">${copy.label}</span>`,
    `    <p class="blog-helpful-count" hidden></p>`,
    `    <canvas class="blog-helpful-confetti" aria-hidden="true"></canvas>`,
    `</div>`,
  ].join("\n");
}

/**
 * The full generated region: switcher then like button, at one consistent
 * position — end of the post body, before the signup box and Sources.
 */
export function renderPostComponents(post: BlogPost, indent = ""): string {
  const parts = [renderLangSwitch(post), renderHelpfulWidget(post)].filter(
    (p) => p.length > 0,
  );
  const body = parts.join("\n\n");
  return [
    indent + BEGIN_MARKER,
    indentLines(body, indent),
    indent + END_MARKER,
  ].join("\n");
}
